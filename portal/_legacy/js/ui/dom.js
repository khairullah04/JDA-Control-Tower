export function ring(pct) {
  const r = 26, c = 2 * Math.PI * r, off = c - (Math.min(pct, 100) / 100) * c;
  return `<div class="ring-wrap"><svg width="64" height="64"><circle class="ring-bg" cx="32" cy="32" r="${r}"/>
    <circle class="ring-fg" cx="32" cy="32" r="${r}" stroke-dasharray="${c}" stroke-dashoffset="${off}"/></svg>
    <div class="ring-label">${Math.round(pct)}%</div></div>`;
}
